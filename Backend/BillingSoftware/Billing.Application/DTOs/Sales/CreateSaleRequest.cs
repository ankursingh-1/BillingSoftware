using System.ComponentModel.DataAnnotations;

namespace Billing.Application.DTOs.Sales
{
    public class CreateSaleRequest
    {
        [Range(1, int.MaxValue, ErrorMessage = "Select a customer.")]
        public int CustomerId { get; set; }

        [Required(ErrorMessage = "At least one item is required.")]
        [MinLength(1, ErrorMessage = "At least one item is required.")]
        [MaxLength(200, ErrorMessage = "A sale cannot have more than 200 items.")]
        public List<CreateSaleItemRequest> Items { get; set; } = new();

        /// <summary>
        /// Payments received at the time of sale. Empty = unpaid (credit sale).
        /// The total may be less than the invoice total (partial payment) but never more.
        /// </summary>
        [MaxLength(10, ErrorMessage = "A sale cannot have more than 10 payments.")]
        public List<CreateSalePaymentRequest>? Payments { get; set; }

        [StringLength(500, ErrorMessage = "Remarks cannot exceed 500 characters.")]
        public string? Remarks { get; set; }

        /// <summary>
        /// Random id generated by the client for this submission. If the same id arrives
        /// twice (double click, retry after a timeout) the existing sale is returned
        /// instead of creating a second invoice and deducting stock twice.
        /// </summary>
        public Guid? ClientRequestId { get; set; }
    }
}
